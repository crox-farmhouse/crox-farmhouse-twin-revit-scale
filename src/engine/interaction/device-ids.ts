import * as THREE from 'three';

/**
 * Stable, build-order-independent interactable ids.
 *
 * Registration still allocates legacy `door-N` / `drawer-N` / `bifold-cupboard-N` / `toggle-N`
 * ids (they are written into mesh userData and must not change), but those numbers shift whenever
 * a zone module adds or removes a door. Stable ids are derived from scene-graph names instead:
 *
 *   `door:<name>`             e.g. `door:utility.stableDoor.lowerLeafGroup`
 *   `door:<ancestor>@x,z`     unnamed leaves: nearest meaningfully-named ancestor + hinge world XZ
 *   `drawer:<name>`, `bifold-cupboard:<name>`, `toggle:<name>`
 *
 * Names that collide get the `@x,z` hinge position appended (for every colliding entry, so the
 * result never depends on registration order).
 */

export type StableIdKind = 'door' | 'drawer' | 'bifold-cupboard' | 'toggle';

/** One object to derive a stable id for. `primary` is preferred over `secondary`. */
export interface StableIdSource {
  readonly legacyId: string;
  readonly kind: StableIdKind;
  /** Object whose position anchors the `@x,z` fallback (hinge pivot or drawer group). */
  readonly anchor: THREE.Object3D;
  readonly primary: THREE.Object3D | undefined;
  readonly secondary: THREE.Object3D | undefined;
}

const AUTO_GENERATED_NAME = /(^|[._])(part|group)_\d+$/;

/** True for names produced by the scene auto-namer (`foo.part_3`, `foo.group_2`). */
export function isAutoGeneratedName(name: string): boolean {
  return AUTO_GENERATED_NAME.test(name);
}

function meaningfulName(obj: THREE.Object3D | undefined): string | undefined {
  if (!obj || obj.name === '' || isAutoGeneratedName(obj.name)) return undefined;
  return obj.name.replace(/\.pivot$/, '');
}

function nearestNamedAncestor(obj: THREE.Object3D): string {
  let cur = obj.parent;
  while (cur) {
    const name = meaningfulName(cur);
    if (name !== undefined) return name;
    cur = cur.parent;
  }
  return 'scene';
}

const tmpLocal = new THREE.Matrix4();
const tmpWorld = new THREE.Matrix4();
const tmpPos = new THREE.Vector3();

/**
 * World XZ of `obj` composed from local transforms (does not touch `matrixWorld`, so deriving ids
 * never mutates scene state), rounded to 0.1 m.
 */
function worldXzTag(obj: THREE.Object3D): string {
  tmpWorld.identity();
  let cur: THREE.Object3D | null = obj;
  while (cur) {
    tmpLocal.compose(cur.position, cur.quaternion, cur.scale);
    tmpWorld.premultiply(tmpLocal);
    cur = cur.parent;
  }
  tmpPos.setFromMatrixPosition(tmpWorld);
  const fmt = (v: number): string => {
    const rounded = Math.round(v * 10) / 10;
    return (Object.is(rounded, -0) ? 0 : rounded).toFixed(1);
  };
  return `@${fmt(tmpPos.x)},${fmt(tmpPos.z)}`;
}

/** Derives stable ids for `sources`. Returns legacyId -> stableId. */
export function deriveStableIds(sources: readonly StableIdSource[]): Map<string, string> {
  const base = new Map<string, string>();
  const counts = new Map<string, number>();
  for (const src of sources) {
    const named = meaningfulName(src.primary) ?? meaningfulName(src.secondary);
    const key =
      named !== undefined
        ? `${src.kind}:${named}`
        : `${src.kind}:${nearestNamedAncestor(src.anchor)}${worldXzTag(src.anchor)}`;
    base.set(src.legacyId, key);
    counts.set(key, (counts.get(key) ?? 0) + 1);
  }

  const result = new Map<string, string>();
  const used = new Set<string>();
  for (const src of sources) {
    let key = base.get(src.legacyId) ?? `${src.kind}:${src.legacyId}`;
    if ((counts.get(key) ?? 0) > 1 && !key.includes('@')) {
      key = `${key}${worldXzTag(src.anchor)}`;
    }
    let unique = key;
    for (let n = 2; used.has(unique); n += 1) unique = `${key}#${n}`;
    used.add(unique);
    result.set(src.legacyId, unique);
  }
  return result;
}
